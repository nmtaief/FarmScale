# --- Tool Schemas by Provider ---
def get_openai_tool_schema() -> Dict[str, Any]:
    """Returns OpenAI / LiteLLM function calling tool format."""
    return {
        "type": "function",
        "function": {
            "name": TOOL_NAME,
            "description": TOOL_DESCRIPTION,
            "parameters": TOOL_PARAMETERS_SCHEMA
        }
    }

def get_gemini_tool_schema() -> Dict[str, Any]:
    """Returns Google Gemini function declaration format."""
    return {
        "function_declarations": [
            {
                "name": TOOL_NAME,
                "description": TOOL_DESCRIPTION,
                "parameters": TOOL_PARAMETERS_SCHEMA
            }
        ]
    }

def get_anthropic_tool_schema() -> Dict[str, Any]:
    """Returns Anthropic Claude tool format."""
    return {
        "name": TOOL_NAME,
        "description": TOOL_DESCRIPTION,
        "input_schema": TOOL_PARAMETERS_SCHEMA
    }

def get_all_tool_schemas() -> Dict[str, Any]:
    """Returns tool schemas in all common formats for easy client configuration."""
    return {
        "tool_name": TOOL_NAME,
        "description": TOOL_DESCRIPTION,
        "parameters": TOOL_PARAMETERS_SCHEMA,
        "openai_format": get_openai_tool_schema(),
        "gemini_format": get_gemini_tool_schema(),
        "anthropic_format": get_anthropic_tool_schema()
    }

# --- Tolerant Argument Normalizer ---
def normalize_llm_arguments(args: Dict[str, Any]) -> Dict[str, Any]:
    """Normalizes slightly loose or fuzzy arguments generated by various LLM models."""
    out = dict(args)

    # 1. Normalize Goal
    raw_goal = str(out.get("goal", "")).lower().strip().replace("-", "_").replace(" ", "_")
    if any(k in raw_goal for k in ["cash", "money", "profit", "commercial", "earning", "yield", "লাভ", "টাকা", "মুনাফা"]):
        out["goal"] = "cash_crop"
    elif any(k in raw_goal for k in ["fertility", "nutrient", "nitrogen", "organic", "replenish", "উর্বরতা", "নাইট্রোজেন", "জৈব"]):
        out["goal"] = "soil_fertility"
    elif any(k in raw_goal for k in ["preservation", "protection", "erosion", "drought", "conserve", "barind", "ক্ষয়", "সংরক্ষণ", "খরা"]):
        out["goal"] = "land_preservation"
    elif any(k in raw_goal for k in ["cultivab", "easy", "manage", "risk", "সহজ", "চাষযোগ্য"]):
        out["goal"] = "cultivability"
    else:
        out["goal"] = "cash_crop"

    # 2. Normalize District / Upazila from generic 'location' field if LLM provided one
    if "location" in out and not out.get("upazila") and not out.get("district"):
        loc_str = str(out["location"]).lower()
        from .layer1_llm import RAJSHAHI_UPAZILAS, RAJSHAHI_DISTRICTS
        for u in RAJSHAHI_UPAZILAS:
            if u.lower() in loc_str:
                out["upazila"] = u
                out["district"] = RAJSHAHI_UPAZILAS[u][0]
                break
        if not out.get("district"):
            for d in RAJSHAHI_DISTRICTS:
                if d.lower() in loc_str:
                    out["district"] = d
                    break

    if not out.get("district"):
        out["district"] = "Rajshahi"

    # 3. Normalize Season
    raw_season = str(out.get("season", "annual")).lower().strip()
    if any(k in raw_season for k in ["rabi", "winter", "শীত", "রবি"]):
        out["season"] = "rabi"
    elif any(k in raw_season for k in ["kharif 1", "kharif_1", "summer", "গ্রীষ্ম"]):
        out["season"] = "kharif_1"
    elif any(k in raw_season for k in ["kharif 2", "kharif_2", "monsoon", "বর্ষা"]):
        out["season"] = "kharif_2"
    else:
        out["season"] = "annual"

    # 4. Normalize Language
    raw_lang = str(out.get("language", "en")).lower().strip()
    out["language"] = "bn" if "bn" in raw_lang or "bengali" in raw_lang or "বাংলা" in raw_lang else "en"

    # 5. Top K bounds
    try:
        out["top_k"] = max(1, min(5, int(out.get("top_k", 3))))
    except (ValueError, TypeError):
        out["top_k"] = 3

    # 6. Latitude & Longitude preservation
    if out.get("latitude") is not None:
        try:
            out["latitude"] = float(out["latitude"])
        except (ValueError, TypeError):
            pass
    if out.get("longitude") is not None:
        try:
            out["longitude"] = float(out["longitude"])
        except (ValueError, TypeError):
            pass

    return out

# --- Tool Execution Engine ---
def execute_ml_tool_call(arguments: Dict[str, Any]) -> Dict[str, Any]:
    """Executes the tool call against the Layer 3 XGBoost ML Model and returns LLM-optimized payload."""
    norm_args = normalize_llm_arguments(arguments)
    svc = get_service()
    svc.ensure_model_trained()

    district = norm_args.get("district", "Rajshahi")
    upazila = norm_args.get("upazila")
    goal = norm_args["goal"]
    season = norm_args["season"]
    lang = norm_args["language"]
    top_k = norm_args["top_k"]

    lat = norm_args.get("latitude")
    lon = norm_args.get("longitude")

    # Run recommendation through the service
    rec = svc.recommend(
        district=district,
        upazila=upazila,
        lat=lat,
        lon=lon,
        goal=goal,
        season=season,
        language=lang,
        top_k=top_k
    )

    location_name = upazila if upazila else district
    telemetry = rec["data_sources_used"]
    rotations = rec["top_rotations"]
    ans = rec["plain_language_answer"]

    # Construct prompt-injection text designed specifically for an LLM to cite
    prompt_context = _build_prompt_context_for_llm(
        location_name=location_name,
        district=district,
        goal=goal,
        season=season,
        lang=lang,
        telemetry=telemetry,
        rotations=rotations,
        model_version=rec["ml_model_metadata"]["version"]
    )

    return {
        "status": "success",
        "tool_name": TOOL_NAME,
        "arguments_used": norm_args,
        "query_analysis": rec["query_analysis"],
        "telemetry_used": telemetry,
        "ml_metadata": rec["ml_model_metadata"],
        "ranked_rotations": rotations,
        "plain_language_answer": ans,
        "llm_prompt_context": prompt_context,
        "instruction_for_llm": (
            "Present these top 3 ML-ranked crop rotations to the farmer. "
            "Highlight the specific reasons why each option was selected based on the real NASA telemetry (temperature, rainfall, soil moisture, and pH). "
            f"Write the response in {'Bengali (বাংলা)' if lang == 'bn' else 'English'}."
        )
    }

def _build_prompt_context_for_llm(
    location_name: str,
    district: str,
    goal: str,
    season: str,
    lang: str,
    telemetry: Dict[str, Any],
    rotations: List[Dict[str, Any]],
    model_version: str
) -> str:
    """Builds a factual, markdown context block ready to be inserted directly into an LLM response or prompt."""
    pw = telemetry["nasa_power_weather"]
    sm = telemetry["smap_soil_moisture"]
    mod = telemetry["modis_vegetation"]
    soil = telemetry["soilgrids_soil"]

    goal_labels = {
        "cash_crop": "Maximizing Cash Profits & Yield",
        "soil_fertility": "Restoring Soil Fertility & Biological Nitrogen",
        "land_preservation": "Land Preservation, Erosion Control & Drought Resilience",
        "cultivability": "Ease of Cultivation, Water Efficiency & Low Risk"
    }

    lines = [
        f"### REAL NASA & SATELLITE TELEMETRY ({location_name}, {district} District)",
        f"- Location Soil: pH {soil['ph']} ({soil.get('texture_group', 'clay loam')}), Soil Organic Carbon: {soil.get('soc_g_kg', 8.0)} g/kg",
        f"- NASA POWER Weather: Mean Temp: {pw['temp_mean_c']}°C, Precip: {pw['precip_mm']} mm, Rootzone Wetness: {pw['rootzone_wetness']}",
        f"- SMAP Root-zone Moisture: {sm['sm_rootzone_m3_m3']} m³/m³ ({sm['sm_rootzone_pctl']}th percentile)",
        f"- MODIS Greenness: NDVI {mod['ndvi']} (VCI: {mod['ndvi_vci']}%)",
        f"- Farmer Target Goal: {goal_labels.get(goal, goal)} (Season span: {season})",
        f"- Machine Learning Engine: XGBoost Regressor ({model_version})",
        "",
        "### TOP ML-RANKED CROP ROTATIONS (Scored 0-100 by XGBoost):"
    ]

    for rot in rotations:
        crops_str = " ➔ ".join(rot.get("pattern", rot.get("crops", [])))
        seasons_str = " | ".join(rot.get("seasons", []))
        score = rot.get("score", rot.get("ml_score"))
        net_n = rot["metrics"]["net_n_balance_kg_ha"]
        duration = round(rot["metrics"]["total_duration_days"])
        yield_t = round(rot["metrics"]["total_yield_t_ha"], 1)

        n_desc = f"+{round(net_n)} kg N/ha fixed" if net_n > 0 else f"{round(net_n)} kg N/ha net removal"
        lines.append(f"{rot['rank']}. **{rot['name']}** (ML Score: **{score}/100**)")
        lines.append(f"   - Pattern: `{crops_str}`")
        lines.append(f"   - Seasonal Timing: {seasons_str} (~{duration} days total cycle)")
        lines.append(f"   - Agronomic Balance: Yield: ~{yield_t} t/ha | Nitrogen Balance: {n_desc}")
        lines.append(f"   - Primary Benefit: {rot['description']}")
        lines.append(f"   - Irrigation Advisory: Rootzone wetness {pw['rootzone_wetness']}; irrigate during critical stages if moisture dips.")
        lines.append("")

    return "\n".join(lines)


# --- Live LLM Agent Pipeline (OpenAI, Gemini, or Simulated Local Agent) ---
def run_llm_agent(
    farmer_query: str,
    provider: Literal["auto", "openai", "gemini", "mock"] = "auto",
    model_name: Optional[str] = None,
    api_key: Optional[str] = None
) -> Dict[str, Any]:
    """End-to-End LLM Agent interaction:
    1. Sends farmer query + tool definition to the LLM.
    2. LLM decides to call `query_nasa_crop_rotation_ml`.
    3. Tool executes Layer 3 XGBoost ML model.
    4. Tool result returned to LLM.
    5. LLM writes final synthesized response in the farmer's language.
    """
    # Auto-detect provider if key present in env
    openai_key = api_key or os.getenv("OPENAI_API_KEY")
    gemini_key = api_key or os.getenv("GEMINI_API_KEY")

    if provider == "auto":
        if openai_key:
            provider = "openai"
        elif gemini_key:
            provider = "gemini"
        else:
            provider = "mock"

    if provider == "openai" and openai_key:
        return _run_openai_agent(farmer_query, openai_key, model_name or "gpt-4o-mini")
    elif provider == "gemini" and gemini_key:
        return _run_gemini_agent(farmer_query, gemini_key, model_name or "gemini-2.0-flash")
    else:
        return _run_mock_agent(farmer_query)


def _run_openai_agent(query: str, api_key: str, model: str) -> Dict[str, Any]:
    """Runs agent using OpenAI function calling protocol."""
    import openai
    client = openai.OpenAI(api_key=api_key)

    system_prompt = (
        "You are an expert agronomist AI assistant for farmers in Rajshahi Division, Bangladesh. "
        "When a farmer asks for crop rotation advice, you MUST call the `query_nasa_crop_rotation_ml` tool "
        "to obtain real NASA-backed ML predictions. Then explain the top 3 rotations clearly in the farmer's language (English or Bengali)."
    )

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": query}
    ]

    tools = [get_openai_tool_schema()]
    resp = client.chat.completions.create(
        model=model,
        messages=messages,
        tools=tools,
        tool_choice="auto"
    )

    msg = resp.choices[0].message
    if msg.tool_calls:
        tool_call = msg.tool_calls[0]
        call_id = tool_call.id
        fn_args = json.loads(tool_call.function.arguments)

        # Execute XGBoost ML Model
        tool_res = execute_ml_tool_call(fn_args)

        # Feed tool result back to LLM
        messages.append(msg)
        messages.append({
            "role": "tool",
            "tool_call_id": call_id,
            "content": json.dumps(tool_res)
        })

        final_resp = client.chat.completions.create(
            model=model,
            messages=messages
        )
        final_text = final_resp.choices[0].message.content

        return {
            "provider": "openai",
            "model": model,
            "tool_called": tool_call.function.name,
            "tool_arguments": fn_args,
            "tool_result": tool_res,
            "llm_final_response": final_text
        }
    else:
        return {
            "provider": "openai",
            "model": model,
            "tool_called": None,
            "llm_final_response": msg.content
        }


def _run_gemini_agent(query: str, api_key: str, model: str) -> Dict[str, Any]:
    """Runs agent using Google Gemini REST API function calling."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
    headers = {"Content-Type": "application/json"}

    tool_def = {
        "function_declarations": [
            {
                "name": TOOL_NAME,
                "description": TOOL_DESCRIPTION,
                "parameters": TOOL_PARAMETERS_SCHEMA
            }
        ]
    }

    body = {
        "contents": [
            {"role": "user", "parts": [{"text": query}]}
        ],
        "tools": [tool_def]
    }

    with httpx.Client(timeout=30) as client:
        r = client.post(url, headers=headers, json=body)
        if r.status_code != 200:
            raise RuntimeError(f"Gemini API error ({r.status_code}): {r.text}")
        data = r.json()

    candidates = data.get("candidates", [])
    if not candidates:
        raise RuntimeError("Gemini returned no response.")

    part = candidates[0].get("content", {}).get("parts", [{}])[0]
    fn_call = part.get("functionCall")

    if fn_call and fn_call.get("name") == TOOL_NAME:
        fn_args = fn_call.get("args", {})
        tool_res = execute_ml_tool_call(fn_args)

        # Second turn: send tool result to Gemini
        body["contents"].append(candidates[0]["content"])
        body["contents"].append({
            "role": "function",
            "parts": [{
                "functionResponse": {
                    "name": TOOL_NAME,
                    "response": {"output": tool_res}
                }
            }]
        })

        with httpx.Client(timeout=30) as client:
            r2 = client.post(url, headers=headers, json=body)
            data2 = r2.json()

        final_text = data2["candidates"][0]["content"]["parts"][0]["text"]
        return {
            "provider": "gemini",
            "model": model,
            "tool_called": TOOL_NAME,
            "tool_arguments": fn_args,
            "tool_result": tool_res,
            "llm_final_response": final_text
        }
    else:
        return {
            "provider": "gemini",
            "model": model,
            "tool_called": None,
            "llm_final_response": part.get("text", "")
        }


def _run_mock_agent(query: str) -> Dict[str, Any]:
    """Offline / local simulation of LLM tool calling flow when no cloud LLM API key is configured."""
    # 1. Step A & B: Simulate LLM intent extraction
    req_info = understand_request(query)
    simulated_tool_args = {
        "district": req_info["location"]["district"],
        "upazila": req_info["location"]["upazila"],
        "goal": req_info["goal"],
        "season": req_info["season"],
        "language": req_info["language"],
        "top_k": 3
    }

    # 2. Step P & D & E: Execute Layer 3 XGBoost ML Model
    tool_res = execute_ml_tool_call(simulated_tool_args)

    # 3. Step F: LLM formats final answer
    heading = tool_res["plain_language_answer"]["heading"]
    summary = tool_res["plain_language_answer"]["summary"]
    rotations_text = []
    for r in tool_res["plain_language_answer"]["rotations"]:
        reasons_bullet = "\n".join([f"    • {reason}" for reason in r["reasons"]])
        rotations_text.append(f"{r['title']}\n  Pattern: {r['pattern']} | Cycle: {r['seasons']}\n  Reasons:\n{reasons_bullet}\n  Advice: {r['advice']}")

    final_text = f"{heading}\n\n{summary}\n\n" + "\n\n".join(rotations_text) + f"\n\n{tool_res['plain_language_answer']['footer']}"

    return {
        "provider": "simulated_local_agent",
        "model": "rule_based_llm_layer1",
        "tool_called": TOOL_NAME,
        "tool_arguments": simulated_tool_args,
        "tool_result": tool_res,
        "llm_final_response": final_text
    }
